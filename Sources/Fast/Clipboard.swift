    // MARK: - search

    /// The clips the words find, in the words, the page's title and
    /// address, and the app's name; of a kind, if asked.
    func find(_ words: String, kind: Filter = .all) -> [Clip] {
        // The common opening state needs the existing array, not a fresh
        // thousand-element filtered copy on each SwiftUI update.
        if words.isEmpty && kind == .all { return items }
        let needles = words.lowercased().split(separator: " ").map(String.init)
        return items.filter { clip in
            guard kind.admits(clip) else { return false }
            return needles.isEmpty || matches(clip, needles)
        }
    }

    /// The newest clip the words find, for a row in the field's own list:
    /// asked on every key, so it stops at the first.
    func first(_ words: String) -> Clip? {
        let needles = words.lowercased().split(separator: " ").map(String.init)
        guard !needles.isEmpty else { return nil }
        return items.first { matches($0, needles) }
    }

    /// What a clip is found by, lowercased once rather than on every key.
    private var hays: [UUID: [UInt8]] = [:]

    private func matches(_ clip: Clip, _ needles: [String]) -> Bool {
        let hay: [UInt8]
        if let known = hays[clip.id] {
            hay = known
        } else {
            hay = Array([clip.text.prefix(4000), Substring(clip.pageTitle ?? ""), Substring(clip.page?.absoluteString ?? ""), Substring(clip.app ?? "")]
                .joined(separator: " ").lowercased().utf8)
            hays[clip.id] = hay
        }
        // Bytes, not characters: a thousand clips looked through on a key
        // is a thousand memmem calls, not a thousand walks of graphemes.
        return needles.allSatisfy { needle in
            let bytes = Array(needle.utf8)
            return hay.withUnsafeBytes { h in bytes.withUnsafeBytes { n in
                memmem(h.baseAddress, h.count, n.baseAddress, n.count) != nil
            } }
        }
    }

    enum Filter: String, CaseIterable {
        case all = "All Types", text = "Text", links = "Links", images = "Images", colors = "Colors", files = "Files", fast = "From Yab"

        func admits(_ clip: Clip) -> Bool {
            switch self {
            case .all: return true
            case .text: return clip.kind == .text
            case .links: return clip.kind == .link
            case .images: return clip.kind == .image
            case .colors: return clip.kind == .color
            case .files: return clip.kind == .file
            case .fast: return clip.page != nil
            }
        }
    }

    // MARK: - on disk

    /// The history's folder: the index and one file per clip, each sealed.
    nonisolated private static var folder: URL { Store.file("clipboard") }

    private func changed() {
        version += 1
        save()
    }

    private func save() {
        guard !saving else { return }
        saving = true
        DispatchQueue.main.asyncAfter(deadline: .now() + 1) { [weak self] in
            guard let self else { return }
            self.saving = false
            let items = self.items
            self.disk.async {
                guard let key = Clips.key(), let plain = try? JSONEncoder().encode(items),
                      let sealed = try? AES.GCM.seal(plain, using: key).combined else { return }
                try? FileManager.default.createDirectory(at: Clips.folder, withIntermediateDirectories: true)
                try? sealed.write(to: Clips.folder.appendingPathComponent("index"), options: .atomic)
            }
        }
    }

    private func load() {
        let url = Clips.folder.appendingPathComponent("index")
        guard let sealed = try? Data(contentsOf: url), let key = Clips.key(),
              let box = try? AES.GCM.SealedBox(combined: sealed), let plain = try? AES.GCM.open(box, using: key),
              let saved = try? JSONDecoder().decode([Clip].self, from: plain) else { return }
        items = saved
        trim()
        version += 1
    }

    private func write(_ data: [(String, Data)], for id: UUID) {
        disk.async {
            guard let key = Clips.key() else { return }
            var out = Data()
            for (type, bytes) in data {
                let name = Data(type.utf8)
                out.append(contentsOf: withUnsafeBytes(of: UInt32(name.count).bigEndian, Array.init))
                out.append(name)
                out.append(contentsOf: withUnsafeBytes(of: UInt64(bytes.count).bigEndian, Array.init))
                out.append(bytes)
            }
            guard let sealed = try? AES.GCM.seal(out, using: key).combined else { return }
            try? FileManager.default.createDirectory(at: Clips.folder, withIntermediateDirectories: true)
            guard (try? sealed.write(to: Clips.folder.appendingPathComponent(id.uuidString), options: .atomic)) != nil else { return }
            DispatchQueue.main.async {
                // The preview may have opened while its data was still
                // being saved, or while a fresh copy replaced the same row.
                self.previews[id] = nil
                self.objectWillChange.send()
            }
        }
    }

    /// What was kept for a clip: read at once, the files are small and this
    /// is on the way to a paste.
    private func read(_ id: UUID) -> [(String, Data)] {
        let url = Clips.folder.appendingPathComponent(id.uuidString)
        guard let sealed = try? Data(contentsOf: url), let key = Clips.key(),
              let box = try? AES.GCM.SealedBox(combined: sealed), let data = try? AES.GCM.open(box, using: key)
        else { return [] }
        var out: [(String, Data)] = []
        var at = 0
        func take(_ n: Int) -> Data? {
            guard at + n <= data.count else { return nil }
            defer { at += n }
            return data.subdata(in: at..<at + n)
        }
        while at < data.count {
            guard let size = take(4).map({ $0.reduce(0) { $0 << 8 | Int($1) } }), let name = take(size),
                  let length = take(8).map({ $0.reduce(0) { $0 << 8 | Int($1) } }), let bytes = take(length) else { break }
            out.append((String(decoding: name, as: UTF8.self), bytes))
        }
        return out
    }

    private func drop(_ id: UUID) {
        hays[id] = nil
        previews[id] = nil
        disk.async { try? FileManager.default.removeItem(at: Clips.folder.appendingPathComponent(id.uuidString)) }
    }

    // MARK: - the key

    nonisolated private static let service = Store.world.map { "Fast Clipboard (\($0))" } ?? "Fast Clipboard"
    nonisolated(unsafe) private static var cached: SymmetricKey?
    nonisolated private static let keyLock = NSLock()

    /// The history's key, made the first time and kept in the keychain.
    nonisolated static func key() -> SymmetricKey? {
        keyLock.lock()
        defer { keyLock.unlock() }
        if let cached { return cached }
        // A test run is a new binary on every build, which the keychain
        // treats as another app: its key is a file in its own world.
        if Store.testing {
            let file = folder.appendingPathComponent("key")
            if let data = try? Data(contentsOf: file), data.count == 32 {
                cached = SymmetricKey(data: data)
            } else {
                let fresh = SymmetricKey(size: .bits256)
                try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
                try? fresh.withUnsafeBytes { Data($0) }.write(to: file, options: .atomic)
                cached = fresh
            }
            return cached
        }
        let identity: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: "history",
        ]
        var query = identity
        query[kSecReturnData as String] = true
        query[kSecMatchLimit as String] = kSecMatchLimitOne
        var out: CFTypeRef?
        if Vault.quietly({ Keychain.copyMatching(query as CFDictionary, &out) }) == errSecSuccess, let data = out as? Data, data.count == 32 {
            cached = SymmetricKey(data: data)
            return cached
        }
        let fresh = SymmetricKey(size: .bits256)
        var add = identity
        add[kSecValueData as String] = fresh.withUnsafeBytes { Data($0) }
        add[kSecAttrAccessible as String] = kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly
        add[kSecAttrLabel as String] = service
        guard Vault.quietly({ Keychain.add(add as CFDictionary, nil) }) == errSecSuccess else { return nil }
        cached = fresh
        return fresh
    }
