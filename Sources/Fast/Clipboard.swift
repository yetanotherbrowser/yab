import YabStore
import AppKit
import CryptoKit
import Security

/// What you copied, kept on this Mac: the field's Clipboard History (`clip`
/// and Tab, or the row of that name).
///
/// The clipboard says when it changes only by a count, so the count is read
/// once a second, a few nanoseconds, and the clipboard itself only when the
/// count moves. Every kind of thing an app put there is kept, so a paste
/// back into Notion or Slack keeps its formatting; a plain paste takes the
/// text alone.
///
/// Where it came from is the part only a browser knows: copied in Fast, the
/// page and its title go with it, and it can be opened again from the copy.
///
/// Never kept: what a password manager marks concealed or transient, what
/// is copied in a private tab, and anything larger than a big picture. The
/// history is written encrypted, with a key kept in the keychain, and what
/// isn't pinned goes after a month.
@MainActor
final class Clips: ObservableObject {
    static let shared = Clips()

    struct Clip: Codable, Identifiable, Equatable {
        enum Kind: String, Codable { case text, link, image, file, color }

        let id: UUID
        var kind: Kind
        /// The words, the address, the file's path, the color's hex, or for
        /// a picture its size in words.
        var text: String
        /// The app it was copied in.
        var app: String?
        var bundle: String?
        /// Copied in Fast: the page, and what it was called.
        var page: URL?
        var pageTitle: String?
        var first: Date
        var last: Date
        var times: Int
        var pinned: Bool
        /// Every kind of data the app put there, in the order it put them,
        /// kept beside the index in a file of its own.
        var types: [String]
        var bytes: Int
        /// A digest of what was copied, so the same thing copied again is
        /// the same row brought up rather than a second one.
        var digest: String

        /// The first line, for a row.
        var line: String {
            if kind == .file { return URL(fileURLWithPath: text).deletingPathExtension().lastPathComponent }
            let first = text.split(whereSeparator: \.isNewline).first(where: { !$0.allSatisfy(\.isWhitespace) }).map(String.init) ?? text
            return first.trimmingCharacters(in: .whitespaces)
        }

        /// A link's page title when Fast knows it.
        var title: String { kind == .link ? (pageTitle ?? line) : line }
    }

    @Published private(set) var items: [Clip] = []
    /// The last link copied, in any app, while it is still what is on the
    /// clipboard: only in memory, never written anywhere (Noticing).
    var copied: CopiedLink?

    /// A link copied, as the bench hands it over, a --test run's.
    func pretend(_ url: URL, app: String?) {
        guard Store.testing else { return }
        copied = CopiedLink(url: url, at: Hints.now, app: app)
        Hints.shared.compose()
    }
    /// Bumped when anything is added, so a list watching this redraws.
    @Published private(set) var version = 0

    /// Kinds of clipboard data password managers use to say "don't keep".
    static let secret: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Whether a copy is marked not to be kept: neither in the history nor
    /// as the link offered under the field.
    nonisolated static func concealed(_ types: [String]) -> Bool {
        types.contains(where: secret.contains)
    }

    /// How long what isn't pinned is kept, and how many at most.
    static let keep: TimeInterval = 30 * 86_400
    static let most = 1000
    /// Past this, a copy isn't kept (a screenshot is a few megabytes).
    nonisolated static let largest = 12 << 20

    /// The count last seen, nil until the first look has read it.
    private var count: Int?
    /// A look is asking the pasteboard's daemon now.
    private var looking = false
    /// What the main thread's reads of a moved clipboard took, for the
    /// bench (evals/clipboard/look.py).
    private(set) var mainRead = Took()
    struct Took {
        var reads = 0
        var lastMs = 0.0
        var worstMs = 0.0
        mutating func record(_ seconds: CFTimeInterval) {
            reads += 1
            lastMs = seconds * 1000
            worstMs = max(worstMs, lastMs)
        }
    }
    private var pace: ClipPace?
    /// The count the clipboard had after Fast itself put a clip back on it:
    /// that change is not a new copy.
    private var ours: Int?
    private let disk = DispatchQueue(label: "dev.serafim.fast.clips", qos: .utility)
    private var saving = false

    /// An isolated history can supply retained bytes without disk or keychain
    /// access. The shared history keeps its existing encrypted disk reader.
    private let readClipData: ((UUID) -> [(String, Data)])?
    private var previews: [UUID: ClipText] = [:]

    /// The kept words and formatting, opened once for the chosen clip.
    func preview(_ clip: Clip) -> ClipText {
        if let hit = previews[clip.id] { return hit }
        let value = ClipText(clip: clip, data: readClipData?(clip.id) ?? read(clip.id))
        if previews.count >= 8 { previews.removeAll() }
        previews[clip.id] = value
        return value
    }

    init(readClipData: ((UUID) -> [(String, Data)])? = nil) {
        self.readClipData = readClipData
    }

    /// The browser to ask about the page a copy was made on.
    weak var browser: Browser?
    private var privateFront: Bool { (BrowserWindows.shared.activeBrowser ?? browser)?.privateBrowsing == true }

    func start(for browser: Browser) {
        self.browser = browser
        guard pace == nil else { return }
        load()
        // A test run may look far more often, YAB_CLIPS_EVERY seconds, so a
        // look meets a page's copy (evals/clipboard/copy_crash.sh).
        let every = Store.testing ? ProcessInfo.processInfo.environment["YAB_CLIPS_EVERY"].flatMap(Double.init) ?? 1 : 1
        let pace = ClipPace(steady: Store.testing ? every : nil) { Clips.shared.look() }
        pace.start()
        self.pace = pace
    }

    /// Keep the real Foundation callback testable without starting clipboard
    /// reads or creating a browser. This is a synchronous main-run-loop entry,
    /// not a Swift task; executor lookup itself crashed in report #1073.
    static func makeTimer(every: TimeInterval, look: @escaping @MainActor () -> Void) -> Timer {
        let timer = Timer.scheduledTimer(withTimeInterval: max(0.005, every), repeats: true) { _ in
            // Crash #906 faults in executor lookup before look() runs.
            // Foundation delivers this scheduled timer on the main run loop.
            AppKitMainThread.sync { look() }
        }
        timer.tolerance = 0.3
        return timer
    }

    /// Whether the clipboard has changed, and if so, what came.
    ///
    /// The waiting is done off the main thread: even the count is a round
    /// trip to the pasteboard's daemon, and the daemon waits up to 10 s for
    /// a copy another device offered by Universal Clipboard. The main
    /// thread waited all of it, 9.9 s in the middle of the stand's tab
    /// closes, in every Yab on the Mac at once (release gate 0.0.25 again,
    /// docs/evidence/clipboard-stall-2026-10-15.md). So the reading queue
    /// asks whether anything changed, and only then does the main thread
    /// read the count and what came, once the daemon has answered.
    ///
    /// AppKit's object stays on the main thread: NSPasteboard.general is one
    /// object for the whole app, written on the main thread by WebKit for a
    /// page's copy, and nothing in it guards its type cache or its owners.
    /// Read on the queue meanwhile, the count alone too, AppKit crashed
    /// (-[NSPasteboard _updateTypeCacheIfNeeded] against -[NSPasteboard
    /// _setOwner:...], m4 2026-10-19; evals/clipboard/copy_crash.sh and
    /// race.swift). The queue only ever touches a Pasteboard Manager
    /// reference of its own, which goes to CFPasteboard, not AppKit's object.
    func look() {
        look(again: false)
    }

    /// A discarded read may already have synchronized the newer copy, so
    /// the retry checks it even without another modified flag.
    private func look(again: Bool) {
        guard !looking else { return }
        looking = true
        Clips.reading.async {
            let seen = Clips.ready()
            DispatchQueue.main.async {
                MainActor.assumeIsolated {
                    if seen.moved || again { Clips.shared.saw(seen) }
                    else { Clips.shared.looking = false }
                }
            }
        }
    }

    /// Before asking for any data, remember which copy and app it is.
    /// The queue checks that its reference still describes that copy.
    private func saw(_ seen: Seen) {
        let started = CACurrentMediaTime()
        defer { mainRead.record(CACurrentMediaTime() - started) }
        let now = NSPasteboard.general.changeCount
        guard now != count else { looking = false; return }
        // The first look only learns where the count stands.
        if count == nil || ours == now { count = now; looking = false; return }
        let change = Change(count: now, own: seen.own)
        let front = NSWorkspace.shared.frontmostApplication
        Clips.reading.async {
            let before = Clips.ready()
            let same = !before.moved && before.own == change.own
            // Another app may take seconds to fulfill its promise. Only
            // this queue waits; Yab's own copy is read on the main thread.
            let other: Read?? = same && Narrow.clipRead && !change.own ? .some(Clips.readOthers()) : nil
            let after = Clips.ready()
            let current = same && !after.moved && after.own == change.own
            DispatchQueue.main.async {
                MainActor.assumeIsolated {
                    Clips.shared.looking = false
                    guard current else { Clips.shared.look(again: true); return }
                    Clips.shared.came(change, own: after.own, front: front, fetched: other)
                }
            }
        }
    }

    /// A fetched copy belongs only to the count and owner seen before
    /// the wait. A rejected read must not consume the newer count.
    struct Change: Sendable {
        let count: Int
        let own: Bool

        func matches(_ now: Int, own: Bool) -> Bool {
            count == now && self.own == own
        }
    }

    /// What the queue fetched, or Yab's own copy, read on the main thread.
    private func came(_ change: Change, own: Bool, front: NSRunningApplication?, fetched: Read??) {
        let started = CACurrentMediaTime()
        defer { mainRead.record(CACurrentMediaTime() - started) }
        let board = NSPasteboard.general
        let now = board.changeCount
        guard change.matches(now, own: own) else { look(again: true); return }
        // Yab's own put or mark came meanwhile: already this count.
        guard now != count else { return }
        count = now
        if ours == now { return }
        // Whatever came, the link copied before is no longer what is there.
        if copied != nil { copied = nil; Hints.shared.compose() }
        // What the queue read of another app's copy, or, for Yab's own,
        // what the main thread reads now.
        guard let read = fetched ?? Clips.read(board) else { return }
        take(read, front: front, own: change.own)
    }

    // MARK: - taking a copy

    private static let reading = DispatchQueue(label: "dev.serafim.fast.clips.read", qos: .userInitiated)

    /// The reading queue's own reference to the clipboard, only ever used
    /// on `reading`.
    nonisolated(unsafe) private static var carbon: Pasteboard?

    /// On the reading queue: whether the clipboard changed since the last
    /// look, and nothing more. PasteboardSynchronize goes to CFPasteboard
    /// and its daemon, never into AppKit; race.swift took some 20 million
    /// of them a round against a main thread writing as WebKit does,
    /// without a crash. Its data is not read here: a read of a copy this
    /// process made comes back into AppKit off the main thread
    /// ("synchronous promise fulfillment requested from a background
    /// thread") and hung race.swift's main thread, and the flavors' flags
    /// can't tell Yab's copy from another app's.
    nonisolated private static func ready() -> Seen {
        dispatchPrecondition(condition: .onQueue(reading))
        let first = carbon == nil
        if first {
            var made: Pasteboard?
            guard PasteboardCreate(kPasteboardClipboard as CFString, &made) == noErr else { return Seen(moved: false, own: false) }
            carbon = made
        }
        guard let board = carbon else { return Seen(moved: false, own: false) }
        let seen = PasteboardSynchronize(board)
        // The first look learns where the count stands.
        return Seen(moved: first || seen.contains(.modified), own: seen.contains(.clientIsOwner))
    }

    /// What `ready` found: the clipboard moved, and this process owns what
    /// is on it now (a copy made in Yab).
    private struct Seen: Sendable {
        var moved: Bool
        var own: Bool
    }

    /// On the reading queue: `read`, for a copy another app made, from the
    /// queue's own reference to the clipboard (CFPasteboard and its daemon,
    /// never AppKit's one object, as in `ready`). Another app's promise is
    /// waited for here, holding only this queue and the next look.
    nonisolated private static func readOthers() -> Read? {
        dispatchPrecondition(condition: .onQueue(reading))
        guard let board = carbon else { return nil }
        var count: Int = 0
        guard PasteboardGetItemCount(board, &count) == noErr, count > 0 else { return nil }
        var first: (PasteboardItemID, [String])?
        var everything: [String] = []
        for index in 1...count {
            var id: PasteboardItemID?
            var names: CFArray?
            guard PasteboardGetItemIdentifier(board, CFIndex(index), &id) == noErr, let id,
                  PasteboardCopyItemFlavors(board, id, &names) == noErr, let flavors = names as? [String] else { continue }
            if first == nil { first = (id, flavors) }
            everything += flavors
        }
        guard let (id, flavors) = first, !concealed(everything) else { return nil }
        func bytes(_ flavor: String) -> Data? {
            var data: CFData?
            guard PasteboardCopyItemFlavorData(board, id, flavor as CFString, &data) == noErr else { return nil }
            return data as Data?
        }
        // Only what the app itself put there, as NSPasteboardItem's types
        // are: the flavors the system would translate a picture into
        // (another TIFF, a PDF, a PICT) made a 5.6 MB picture count past
        // `largest`, so it was never kept.
        func translated(_ flavor: String) -> Bool {
            var flags: PasteboardFlavorFlags = []
            guard PasteboardGetItemFlavorFlags(board, id, flavor as CFString, &flags) == noErr else { return false }
            return flags.contains(.systemTranslated)
        }
        var data: [(String, Data)] = []
        var total = 0
        var tooBig = false
        for flavor in flavors where !translated(flavor) {
            guard let one = bytes(flavor) else { continue }
            total += one.count
            if total > largest { tooBig = true; break }
            data.append((flavor, one))
        }
        func text(_ flavors: [String]) -> String? {
            for flavor in flavors {
                let one = data.first { $0.0 == flavor }?.1 ?? bytes(flavor)
                if let one, let words = String(data: one, encoding: flavor.contains("utf16") ? .utf16 : .utf8) { return words }
            }
            return nil
        }
        return Read(string: text(["public.utf8-plain-text", "public.utf16-plain-text", "public.utf16-external-plain-text"]),
                    url: text(["public.url"]), file: text(["public.file-url"]),
                    data: tooBig ? [] : data, total: total)
    }

    /// The first item on the clipboard, read whole, or nil for nothing to
    /// keep (none, concealed, or past `largest`).
    private struct Read: Sendable {
        var string: String?
        var url: String?
        var file: String?
        var data: [(String, Data)]
        var total: Int
    }

    private static func read(_ board: NSPasteboard) -> Read? {
        guard let item = board.pasteboardItems?.first else { return nil }
        if concealed(item.types.map(\.rawValue)) || concealed((board.types ?? []).map(\.rawValue)) { return nil }
        var data: [(String, Data)] = []
        var total = 0
        var tooBig = false
        for type in item.types {
            guard let bytes = item.data(forType: type) else { continue }
            total += bytes.count
            if total > largest { tooBig = true; break }
            data.append((type.rawValue, bytes))
        }
        // Too big to keep, but a link in it is still offered.
        return Read(string: item.string(forType: .string), url: item.string(forType: .URL),
                    file: item.string(forType: .fileURL), data: tooBig ? [] : data, total: total)
    }

    private func take(_ item: Read, front: NSRunningApplication?, own: Bool) {
        let mine = own && front?.processIdentifier == ProcessInfo.processInfo.processIdentifier
        // A private tab keeps nothing, the copies made in it included.
        if mine, privateFront { return }
        // A link, as text that is all address or as a URL of its own: the
        // row under the empty field, for a minute and a half.
        if let address = [item.string, item.url]
            .compactMap({ $0?.trimmingCharacters(in: .whitespacesAndNewlines) }).first(where: Clips.isLink),
           let url = URL(string: address) {
            copied = CopiedLink(url: url, at: Hints.now, app: mine ? nil : front?.localizedName)
            Hints.shared.compose()
        }

        let data = item.data
        let total = item.total
        guard !data.isEmpty else { return }

        let string = item.string?.trimmingCharacters(in: .whitespacesAndNewlines)
        var kind = Clip.Kind.text
        var text = string ?? ""
        if let path = item.file.flatMap(URL.init(string:)), path.isFileURL {
            kind = .file
            text = path.path
        } else if (string ?? "").isEmpty, let image = data.first(where: { [NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue].contains($0.0) }),
                  let picture = NSImage(data: image.1) {
            kind = .image
            let size = picture.representations.first.map { CGSize(width: $0.pixelsWide, height: $0.pixelsHigh) } ?? picture.size
            text = "Image (\(Int(size.width)) × \(Int(size.height)))"
        } else if let string, !string.isEmpty {
            if Clips.isLink(string) {
                kind = .link
            } else if Clips.hex(string) != nil {
                kind = .color
            }
        } else {
            return
        }

        let digest = Clips.digest(kind == .image ? data.first { $0.0 != NSPasteboard.PasteboardType.string.rawValue }?.1 ?? Data() : Data(text.utf8))
        let now = Date()
        var page: URL?
        var pageTitle: String?
        if mine, let tab = browser?.active, !tab.isBlank {
            page = tab.address
            pageTitle = tab.label
        }

        if let index = items.firstIndex(where: { $0.digest == digest && $0.kind == kind }) {
            var clip = items.remove(at: index)
            previews[clip.id] = nil
            clip.last = now
            clip.times += 1
            if clip.page == nil, let page { clip.page = page; clip.pageTitle = pageTitle }
            clip.types = data.map(\.0)
            clip.bytes = total
            write(data, for: clip.id)
            items.insert(clip, at: clip.pinned ? 0 : pinnedCount)
        } else {
            let clip = Clip(id: UUID(), kind: kind, text: text, app: front?.localizedName, bundle: front?.bundleIdentifier,
                            page: page, pageTitle: pageTitle, first: now, last: now, times: 1, pinned: false,
                            types: data.map(\.0), bytes: total, digest: digest)
            items.insert(clip, at: pinnedCount)
            write(data, for: clip.id)
        }
        trim()
        changed()
    }

    /// A picture yab put on the clipboard itself (Capture.swift), kept as
    /// a clip from the PNG it already made. Read back from the clipboard
    /// instead, on the main thread, the promise would be made and waited
    /// for there, some 300 ms for a whole page. A clip it replaces, the
    /// same capture in another style, goes.
    func mark(_ changeCount: Int) { ours = changeCount; count = changeCount }

    @discardableResult
    func took(png: Data, digest: String, pixels: CGSize, page: URL?, pageTitle: String?, replacing: UUID?) -> UUID? {
        if let replacing { items.removeAll { $0.id == replacing && !$0.pinned } }
        guard png.count <= Clips.largest, !privateFront else { changed(); return nil }
        let now = Date()
        let type = NSPasteboard.PasteboardType.png.rawValue
        let clip = Clip(id: UUID(), kind: .image, text: "Image (\(Int(pixels.width)) × \(Int(pixels.height)))",
                        app: nil, bundle: Bundle.main.bundleIdentifier, page: page, pageTitle: pageTitle,
                        first: now, last: now, times: 1, pinned: false, types: [type], bytes: png.count, digest: digest)
        items.insert(clip, at: pinnedCount)
        write([(type, png)], for: clip.id)
        trim()
        changed()
        return clip.id
    }

    private var pinnedCount: Int { items.prefix { $0.pinned }.count }

    nonisolated static func isLink(_ text: String) -> Bool {
        guard !text.contains(where: \.isWhitespace), let url = URL(string: text),
              let scheme = url.scheme?.lowercased(), ["http", "https"].contains(scheme), url.host() != nil
        else { return false }
        return true
    }

    /// #2F6BFF, 2f6bff, #abc: the color it names.
    nonisolated static func hex(_ text: String) -> NSColor? {
        let bare = text.hasPrefix("#") ? String(text.dropFirst()) : text
        guard [3, 6].contains(bare.count), bare.allSatisfy(\.isHexDigit), text.hasPrefix("#") || bare.count == 6,
              bare.contains(where: \.isNumber) || text.hasPrefix("#")
        else { return nil }
        let full = bare.count == 3 ? bare.map { "\($0)\($0)" }.joined() : bare
        return NSColor(hex: full)
    }

    nonisolated static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).prefix(12).map { String(format: "%02x", $0) }.joined()
    }

    /// Past a month, and past a thousand, what isn't pinned goes.
    private func trim() {
        let cutoff = Date().addingTimeInterval(-Clips.keep)
        let gone = items.filter { !$0.pinned && $0.last < cutoff }
        items.removeAll { !$0.pinned && $0.last < cutoff }
        var extra: [Clip] = []
        while items.count > Clips.most, let last = items.lastIndex(where: { !$0.pinned }) {
            extra.append(items.remove(at: last))
        }
        for clip in gone + extra { drop(clip.id) }
    }

    // MARK: - putting one back

    /// The clip on the clipboard again, every kind it came with, or only its
    /// text. Brought to the top, as a copy would bring it.
    func put(_ clip: Clip, plain: Bool = false, on board: NSPasteboard = .general) {
        board.clearContents()
        if plain || clip.kind == .text && clip.types.isEmpty {
            // `text` is the trimmed index/preview, not the copied payload.
            // A plain paste drops formats, never the original whitespace.
            let text = plain && clip.kind == .text
                ? Self.plainText(readClipData?(clip.id) ?? read(clip.id)) ?? clip.text
                : clip.text
            board.setString(clip.kind == .image ? "" : text, forType: .string)
        } else {
            let item = NSPasteboardItem()
            for (type, bytes) in readClipData?(clip.id) ?? read(clip.id) { item.setData(bytes, forType: NSPasteboard.PasteboardType(type)) }
            if item.types.isEmpty { item.setString(clip.text, forType: .string) }
            board.writeObjects([item])
        }
        ours = board.changeCount
        count = board.changeCount
        if let index = items.firstIndex(where: { $0.id == clip.id }) {
            var clip = items.remove(at: index)
            clip.last = Date()
            clip.times += 1
            items.insert(clip, at: clip.pinned ? 0 : pinnedCount)
            changed()
        }
    }

    /// The same standard plain flavors/decoding used by the clipboard reader.
    /// No rich-format conversion: old clips without one retain their fallback.
    private static func plainText(_ data: [(String, Data)]) -> String? {
        for flavor in ["public.utf8-plain-text", "public.utf16-plain-text", "public.utf16-external-plain-text"] {
            guard let bytes = data.first(where: { $0.0 == flavor })?.1 else { continue }
            if let text = String(data: bytes, encoding: flavor.contains("utf16") ? .utf16 : .utf8) { return text }
        }
        return nil
    }

    func pin(_ clip: Clip) {
        guard let index = items.firstIndex(where: { $0.id == clip.id }) else { return }
        var clip = items.remove(at: index)
        clip.pinned.toggle()
        items.insert(clip, at: clip.pinned ? 0 : pinnedCount)
        changed()
    }

    func delete(_ clip: Clip) {
        items.removeAll { $0.id == clip.id }
        drop(clip.id)
        changed()
    }

    /// Delete, and the way back for ⌘Z for a minute: its data stays on disk
    /// that long, and goes at once if the app quits first.
    func deleteUndoably(_ clip: Clip) -> () -> Void {
        guard let at = items.firstIndex(where: { $0.id == clip.id }) else { return {} }
        let gone = items.remove(at: at)
        changed()
        Clips.dropping.insert(gone.id)
        let drop = { [weak self] in
            guard Clips.dropping.remove(gone.id) != nil else { return }
            self?.drop(gone.id)
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 60) { drop() }
        if Clips.quitWatch == nil {
            Clips.quitWatch = NotificationCenter.default.addObserver(forName: NSApplication.willTerminateNotification, object: nil, queue: .main) { _ in
                MainActor.assumeIsolated {
                    for id in Clips.dropping { try? FileManager.default.removeItem(at: Clips.folder.appendingPathComponent(id.uuidString)) }
                    Clips.dropping = []
                }
            }
        }
        return { [weak self] in
            guard let self, Clips.dropping.remove(gone.id) != nil, !items.contains(where: { $0.id == gone.id }) else { return }
            items.insert(gone, at: min(at, items.count))
            changed()
        }
    }

